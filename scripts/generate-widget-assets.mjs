import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

/**
 * Builds the widget bundle and regenerates `src/generated-assets.ts`, which the
 * Worker bundles so `/src/bangumi.js|css` stay stable, cacheable URLs.
 *
 * `builtAt` changes only when the produced bytes change, so rebuilding
 * unchanged source is reproducible and does not dirty the tracked tree.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageDir = resolve(root, 'packages/widget')
const generatedPath = resolve(packageDir, 'src/generated-assets.ts')

const requireFromPackage = createRequire(resolve(packageDir, 'package.json'))
const { build } = await import(pathToFileURL(requireFromPackage.resolve('vite')).href)
await build({ root: packageDir, configFile: resolve(packageDir, 'vite.config.ts') })

const [js, css] = await Promise.all([
  readFile(resolve(packageDir, 'dist/bangumi.js'), 'utf8'),
  readFile(resolve(packageDir, 'dist/bangumi.css'), 'utf8'),
])

const contentHash = createHash('sha256').update(js).update('\0').update(css).digest('hex')

let previous = null
try {
  const existing = await readFile(generatedPath, 'utf8')
  const contentHash = existing.match(/"contentHash":\s*"([0-9a-f]{64})"/)?.[1]
  const builtAt = existing.match(/"builtAt":\s*"([^"]+)"/)?.[1]
  if (contentHash && builtAt) previous = { contentHash, builtAt }
} catch {
  // first generation
}

const builtAt = previous?.contentHash === contentHash ? previous.builtAt : new Date().toISOString()

const output = `// Generated by scripts/generate-widget-assets.mjs — do not edit by hand.
// Source: packages/widget/src/app (Vite library build).

export const generatedWidgetJs = ${JSON.stringify(js)}

export const generatedWidgetCss = ${JSON.stringify(css)}

export const generatedBuildInfo = {
  "builtAt": ${JSON.stringify(builtAt)},
  "contentHash": ${JSON.stringify(contentHash)}
} as const
`

await writeFile(generatedPath, output)

console.log(JSON.stringify({
  status: 'ok',
  stage: 'generate_widget_assets',
  bytes: { js: Buffer.byteLength(js), css: Buffer.byteLength(css) },
  contentHash,
  builtAt,
}))
